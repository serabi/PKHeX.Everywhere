import { createServer } from 'node:http'
import { readFile, readdir } from 'node:fs/promises'
import { resolve, extname, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import assert from 'node:assert/strict'

const sdk = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const fixtures = process.env.SERABI_FIXTURE_DIR
if (!fixtures) throw new Error('Set SERABI_FIXTURE_DIR to the synthetic fixtures generated by Reader.Tests.')
const halfFixtures = (await readdir(fixtures)).filter(name => name.startsWith('E-half-') && name.endsWith('.sav')).map(name => name.slice(0, -4))
assert.equal(halfFixtures.length, 13)
const playwrightModule = process.env.SERABI_PLAYWRIGHT_MODULE ?? 'playwright'
const { chromium } = await import(playwrightModule.startsWith('/') ? pathToFileURL(playwrightModule).href : playwrightModule)
const requests = []
const server = createServer(async (request, response) => {
  requests.push({ method: request.method, url: request.url })
  try {
    if (request.url === '/') {
      response.setHeader('content-type', 'text/html')
      response.end('<!doctype html><title>Save reader test</title>')
      return
    }
    const url = new URL(request.url, 'http://localhost')
    const root = url.pathname.startsWith('/fixtures/') ? fixtures : sdk
    const relative = url.pathname.startsWith('/fixtures/') ? url.pathname.slice('/fixtures/'.length) : url.pathname.slice(1)
    const file = resolve(root, relative)
    if (!file.startsWith(resolve(root) + '/')) throw new Error('Invalid path')
    const mime = { '.js': 'application/javascript', '.wasm': 'application/wasm', '.json': 'application/json' }[extname(file)]
    if (mime) response.setHeader('content-type', mime)
    response.end(await readFile(file))
  } catch {
    response.writeHead(404).end()
  }
})
await new Promise((done) => server.listen(0, '127.0.0.1', done))
const url = `http://127.0.0.1:${server.address().port}`
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage()
  const browserRequests = []
  page.context().on('request', (request) => browserRequests.push({ method: request.method(), url: request.url() }))
  page.on('pageerror', (error) => console.error(error.message))
  page.on('console', (message) => { if (message.type() === 'error') console.error(message.text()) })
  await page.goto(url)
  const result = await page.evaluate(async (halfFixtures) => {
    const { createSaveReader } = await import('/dist/index.js')
    const progress = []
    const started = performance.now()
    const reader = await createSaveReader({ baseUrl: '/assets/', onProgress: (value) => progress.push(value) })
    const preparingMs = performance.now() - started
    const results = []
    for (const version of ['C', 'C-empty', 'FR', 'LG', 'HG', 'SS', 'US', 'UM', 'GP', 'BD', 'HG-checksum-invalid', 'SS-checksum-invalid', 'FR-checksum-invalid']) {
      const bytes = new Uint8Array(await (await fetch(`/fixtures/${version}.sav`)).arrayBuffer())
      const before = await crypto.subtle.digest('SHA-256', bytes)
      const started = performance.now()
      let inspected = await reader.inspect(bytes, { fileName: `${version}.sav` })
      const formatChoice = inspected.status === 'error' && inspected.code === 'format-choice-required'
      if (formatChoice && inspected.pkhexGame) {
        inspected = await reader.inspect(bytes, { fileName: `${version}.sav`, formatId: 'pkhex' })
      }
      const after = await crypto.subtle.digest('SHA-256', bytes)
      results.push({ version, inspected, formatChoice, ms: performance.now() - started,
        unchanged: new Uint8Array(before).every((byte, i) => byte === new Uint8Array(after)[i]) })
    }
    const dateResults = []
    const names = ['HG', 'SS', 'SN', 'MN', 'US', 'UM'].flatMap(version =>
      ['2000-02-29', '2024-02-29', ['HG', 'SS'].includes(version) ? '2099-12-31' : '2050-12-31'].map(date => `${version}-date-${date}`))
    names.push(...['C', 'FR', 'HG', 'US', 'BD'].map(version => `${version}-trainer`))
    names.push('HG-date-absent-0', 'US-date-absent-0', 'HG-date-absent-4294967295', 'US-date-absent-4294967295', 'LG-date-absent-123456789')
    for (const name of names) {
      const bytes = new Uint8Array(await (await fetch(`/fixtures/${name}.sav`)).arrayBuffer())
      const expected = await (await fetch(`/fixtures/${name}.json`)).json()
      const before = await crypto.subtle.digest('SHA-256', bytes)
      const inspected = await reader.inspect(bytes, { formatId: 'pkhex' })
      const after = await crypto.subtle.digest('SHA-256', bytes)
      dateResults.push({ name, inspected, expectedDate: expected.startDate, expectedTrainer: expected.trainer, expectedPlaySeconds: expected.playSeconds,
        unchanged: new Uint8Array(before).every((byte, i) => byte === new Uint8Array(after)[i]) })
    }
    const halfResults = []
    for (const name of halfFixtures) {
      const bytes = new Uint8Array(await (await fetch(`/fixtures/${name}.sav`)).arrayBuffer())
      const expected = await (await fetch(`/fixtures/${name}.json`)).json()
      const before = await crypto.subtle.digest('SHA-256', bytes)
      const inspected = await reader.inspect(bytes, name.endsWith('hack-choice') ? {} : { formatId: 'pkhex' })
      const after = await crypto.subtle.digest('SHA-256', bytes)
      halfResults.push({ name, inspected, expected,
        unchanged: new Uint8Array(before).every((byte, i) => byte === new Uint8Array(after)[i]) })
    }
    const invalid = await reader.inspect(new Uint8Array([1, 2, 3]))
    reader.dispose()
    let disposed = false
    try { await reader.inspect(new Uint8Array([1])) } catch (error) { disposed = error.name === 'AbortError' }
    const controller = new AbortController()
    const preparing = createSaveReader({ baseUrl: '/assets/', signal: controller.signal })
    controller.abort()
    let cancelled = false
    try { await preparing } catch (error) { cancelled = error.name === 'AbortError' }
    return { preparingMs, progress, results, dateResults, halfResults, invalid, disposed, cancelled }
  }, halfFixtures)
  for (const { version, inspected, unchanged } of result.results) {
    const expected = JSON.parse(await readFile(resolve(fixtures, `${version}.json`), 'utf8'))
    assert.deepEqual(inspected, expected, version)
    assert.equal(inspected.status, 'ok', `${version}: ${JSON.stringify(inspected)}`)
    assert.deepEqual(inspected.pokedex.caughtSpecies, version === 'C-empty' ? [] : version.endsWith('checksum-invalid') ? [25] : [25, 133], version)
    assert.ok(inspected.game.versions.includes(version.replace('-empty', '').replace('-checksum-invalid', '')), version)
    if (['C', 'FR', 'LG', 'HG', 'SS', 'US', 'UM'].includes(version))
      assert.ok(inspected.pokedex.seenSpecies.includes(1), `${version}: seen-only species`)
    assert.equal(unchanged, true, version)
  }
  for (const { name, inspected, expectedDate, expectedTrainer, expectedPlaySeconds, unchanged } of result.dateResults) {
    assert.equal(inspected.status, 'ok', name)
    assert.deepEqual(inspected.trainer, expectedTrainer, name)
    assert.equal(Object.hasOwn(inspected, 'trainer'), expectedTrainer !== undefined, name)
    assert.equal(inspected.playSeconds, expectedPlaySeconds, name)
    assert.equal(Object.hasOwn(inspected, 'playSeconds'), expectedPlaySeconds !== undefined, name)
    assert.equal(inspected.startDate, expectedDate, name)
    assert.equal(Object.hasOwn(inspected, 'startDate'), expectedDate !== undefined, name)
    assert.equal(unchanged, true, name)
  }
  for (const { name, inspected, expected, unchanged } of result.halfResults) {
    assert.equal(inspected.status, expected.status, name)
    assert.equal(inspected.code, expected.code, name)
    if (expected.status === 'ok') {
      assert.deepEqual(inspected.game, expected.game, name)
      assert.deepEqual(inspected.pokedex, expected.pokedex, name)
    }
    assert.equal(unchanged, true, name)
  }
  assert.equal(result.invalid.code, 'invalid-save')
  assert.equal(result.disposed, true)
  assert.equal(result.cancelled, true)
  assert.ok(requests.every((request) => request.method === 'GET'))
  assert.ok(browserRequests.every((request) => request.method === 'GET' && new URL(request.url).origin === url))
  console.log(JSON.stringify({ preparingMs: result.preparingMs, downloadEvents: result.progress.length,
    results: result.results.map(({ version, inspected, formatChoice, ms, unchanged }) => ({ version, detected: inspected.game.version, formatChoice, ms, unchanged })),
    dateFixtures: result.dateResults.length, halfSizeFixtures: result.halfResults.length, cancelled: result.cancelled, requestMethods: [...new Set(requests.map((request) => request.method))],
    browserRequestOrigins: [...new Set(browserRequests.map((request) => new URL(request.url).origin))] }, null, 2))
} finally {
  await browser.close()
  await new Promise((done) => server.close(done))
}
